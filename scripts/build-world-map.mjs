// Pre-projects the world map into static SVG path data so the browser ships
// no geo libraries. Run: node scripts/build-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEqualEarth, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const countries = feature(topo, topo.objects.countries);

const W = 1000;
const H = 500;
const projection = geoEqualEarth().fitExtent([[10, 10], [W - 10, H - 10]], { type: "Sphere" });
const path = geoPath(projection);

const round = (d) => d.replace(/(\d+\.\d{1})\d+/g, "$1");

const out = countries.features
  .filter((f) => f.properties.name !== "Antarctica")
  .map((f) => ({ id: String(f.id ?? f.properties.name), name: f.properties.name, d: round(path(f) ?? "") }))
  .filter((c) => c.d);

// Market anchor points. These are geographic centres for display only — they
// do not represent office, factory or client locations.
const anchors = {
  pakistan: { label: "Pakistan", lonlat: [69.3, 30.2], countries: ["Pakistan"] },
  uk: { label: "United Kingdom", lonlat: [-2.0, 53.5], countries: ["United Kingdom"] },
  europe: {
    label: "Europe",
    lonlat: [10.0, 49.5],
    countries: ["Germany", "France", "Netherlands", "Belgium", "Spain", "Italy", "Portugal", "Denmark", "Sweden", "Poland", "Austria", "Ireland", "Finland", "Czechia", "Norway", "Switzerland", "Greece"],
  },
  us: { label: "United States", lonlat: [-98.5, 39.5], countries: ["United States of America"] },
  canada: { label: "Canada", lonlat: [-100, 57], countries: ["Canada"] },
  australia: { label: "Australia", lonlat: [134, -25.5], countries: ["Australia"] },
  newzealand: { label: "New Zealand", lonlat: [172.5, -41.5], countries: ["New Zealand"] },
  gulf: { label: "Gulf region", lonlat: [52, 24.5], countries: ["United Arab Emirates", "Saudi Arabia", "Qatar", "Kuwait", "Oman"] },
};

const markets = Object.fromEntries(
  Object.entries(anchors).map(([k, v]) => {
    const [x, y] = projection(v.lonlat);
    return [k, { label: v.label, x: +x.toFixed(1), y: +y.toFixed(1), countries: v.countries }];
  }),
);

const sphere = round(path({ type: "Sphere" }));
const file = `// Generated by scripts/build-world-map.mjs — do not edit by hand.
export const worldMap = ${JSON.stringify({ width: W, height: H, sphere, countries: out, markets })} as const;
`;
writeFileSync(new URL("../data/world-map.ts", import.meta.url), file);
console.log("countries:", out.length, "bytes:", file.length);
